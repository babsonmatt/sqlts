import { resolve, relative } from "node:path";
import { mkdir, rename, writeFile, readFile } from "node:fs/promises";
import { extract } from "../src/extract.ts";
import { render } from "../src/parts.ts";
import { alias, analyzeQuery, tooling } from "../src/adapter/reylo.ts";
import type { Artifact } from "../src/runtime.ts";
import { validatePlaceholders } from "../src/validate.ts";
import { normalizeGeneratedType } from "../src/generated-types.ts";
import { queryMarkdown } from "../src/preview.ts";

export async function generate(files: string[], destination = ".inline/sql.ts") {
  const queries = (
    await Promise.all(
      files.map(async (file) => extract(await readFile(file, "utf8"), resolve(file))),
    )
  ).flat();
  const ids = new Set<string>();
  for (const q of queries) {
    if (ids.has(q.id)) throw new Error(`Duplicate query ID '${q.id}'`);
    ids.add(q.id);
  }
  if (!queries.length) throw new Error("No inline queries found");
  const handlers = tooling.mapperHandlers();
  const projectHandle = `inline-${crypto.randomUUID()}`;
  const artifact: Artifact = Object.create(null);
  const types: string[] = [];
  const parameterTypes = new Map<string, string>();
  const rowTypes = new Map<string, string>();
  const registry: string[] = [];
  const overloads: string[] = [];
  let count = 0;
  const started = performance.now();
  try {
    await handlers.openProject({ projectHandle, configFileName: resolve("tsconfig.json") });
    for (const q of queries) {
      artifact[q.id] = Object.create(null);
      const inputs: string[] = [],
        rows: string[] = [];
      const contractsByArity = new Map<number, string>();
      for (const parts of q.variants) {
        validatePlaceholders(parts);
        const { named, values } = render(parts);
        const fileName = resolve(".inline", `shape-${count}.sql`);
        const result = await analyzeQuery({ projectHandle, fileName, content: named }, handlers);
        const expected = values.map((_, i) => `p${i}`);
        if (
          result.info.params.length !== expected.length ||
          expected.some((p) => !result.info.params.includes(p))
        )
          throw new Error(
            `${q.file}:${q.line}: Interpolations must be SQL values, outside quotes/comments; authored named parameters are unsupported`,
          );
        // A tag's type carries its value tuple, not the literal SQL text. Until we
        // have per-fragment source identity, equal-length variants must agree on
        // each input contract; otherwise a tuple could match the wrong branch.
        const contract = JSON.stringify(expected.map((p) => result.info.inputs?.[p]));
        const previous = contractsByArity.get(expected.length);
        if (previous !== undefined && previous !== contract)
          throw new Error(
            `${q.file}:${q.line}: Ambiguous input types across SQL shapes with ${expected.length} bindings; use separate query IDs for these branches`,
          );
        contractsByArity.set(expected.length, contract);
        const paramsType = normalizeGeneratedType(alias(result.text, "Params"));
        let paramsName = parameterTypes.get(paramsType);
        if (!paramsName && expected.length) {
          paramsName = `Params${parameterTypes.size}`;
          parameterTypes.set(paramsType, paramsName);
          types.push(`type ${paramsName} = ${paramsType};`);
        }
        const rowType = normalizeGeneratedType(alias(result.text, "Row"));
        let rowName = rowTypes.get(rowType);
        if (!rowName) {
          rowName = `Row${rowTypes.size}`;
          rowTypes.set(rowType, rowName);
          types.push(`type ${rowName} = ${rowType};`);
        }
        inputs.push(
          `readonly [${expected.map((p) => `${paramsName}[${JSON.stringify(p)}]`).join(", ")}]`,
        );
        rows.push(rowName);
        artifact[q.id]![named] = result.info;
        count++;
      }
      registry.push(
        `${JSON.stringify(q.id)}: { inputs: ${[...new Set(inputs)].join(" | ")}; row: ${[...new Set(rows)].join(" | ")} }`,
      );
      const documentation = queryMarkdown(q, true)
        .replaceAll("*/", "* /")
        .split("\n")
        .map((line) => ` * ${line}`)
        .join("\n");
      overloads.push(
        `/**\n${documentation}\n */\n(id: ${JSON.stringify(q.id)}): QueryTag<Queries[${JSON.stringify(q.id)}]["inputs"], Queries[${JSON.stringify(q.id)}]["row"]>;`,
      );
    }
    const runtimePath = relative(resolve(destination, ".."), resolve("src/runtime.ts"));
    const code = `// Generated by bun run generate. Edit the inline queries, not this file.\nimport { createSql, type Artifact, type Sql, type QueryTag } from ${JSON.stringify(runtimePath.startsWith(".") ? runtimePath : `./${runtimePath}`)};\n${types.join("\n")}\ntype Queries = {\n${registry.join(";\n")}\n};\ninterface DocumentedSql extends Sql<Queries> { query: {\n${overloads.join("\n")}\n<K extends keyof Queries>(id: K): QueryTag<Queries[K]["inputs"], Queries[K]["row"]>;\n} }\nconst artifact = ${JSON.stringify(artifact, null, 2)} as Artifact;\nexport const sql: DocumentedSql = createSql<Queries>(artifact);\n`;
    // One atomic artifact: types and executable metadata always advance together.
    await mkdir(resolve(destination, ".."), { recursive: true });
    const formatted = await (await import("oxfmt")).format(destination, code);
    if (formatted.errors.length) throw new Error(JSON.stringify(formatted.errors));
    const temp = `${destination}.${crypto.randomUUID()}.tmp`;
    await writeFile(temp, formatted.code);
    await rename(temp, destination);
    const stats = {
      queries: queries.length,
      shapes: count,
      milliseconds: +(performance.now() - started).toFixed(2),
    };
    console.log(stats);
    return stats;
  } finally {
    await handlers.closeProject({ projectHandle });
    await tooling.releaseConnections();
  }
}
if (import.meta.main) {
  const files = process.argv.slice(2);
  if (!files.length)
    for await (const file of new Bun.Glob("examples/**/queries.ts").scan(".")) files.push(file);
  await generate(files);
}
